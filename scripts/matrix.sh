#!/usr/bin/env bash
# Run the test suite on each backend and write MATRIX.md.
#
#   scripts/matrix.sh              # interp js py lua rust csharp java elixir
#   scripts/matrix.sh js py        # just these
#
# Per-backend logs go to build/matrix/<backend>.log. A backend that fails to
# run at all (missing toolchain, CLI crash) is reported as "no run", not as
# a pass. Exit status is non-zero if any backend failed or did not run.
set -uo pipefail
cd "$(dirname "$0")/.."
root=$(pwd)
out=$root/build/matrix
mkdir -p "$out"
backends=("$@")
[ ${#backends[@]} -eq 0 ] && backends=(interp js py lua rust csharp java elixir)

rows=()
bad=0
for b in "${backends[@]}"; do
  echo "==> $b"
  start=$(date +%s)
  # A stale test report from an earlier run is counted again by the CLI
  # ("Tests passed: 15 of 10"), so each backend starts from a clean output.
  rm -rf "$root/temper.out/$b"
  # elixir lives in a separate checkout (../temper-elixir); bin/temper-elixir wraps it.
  cli=bin/temper
  [ "$b" = elixir ] && cli=bin/temper-elixir
  "$cli" test -w "$root" -ign "$root/.temperignore" -b "$b" >"$out/$b.log" 2>&1
  secs=$(( $(date +%s) - start ))
  summary=$(grep -E '^Tests passed: ' "$out/$b.log" | tail -1)
  if [ -z "$summary" ]; then
    reason=$(grep -vE '^\s*$|^\s+at ' "$out/$b.log" | grep -iE 'error|exception|failed|not found' | head -1 | cut -c1-120)
    rows+=("| $b | no run | ${secs}s | ${reason:-see build/matrix/$b.log} |")
    bad=1
    echo "    no run: ${reason:-see build/matrix/$b.log}"
    continue
  fi
  passed=${summary#Tests passed: }
  fails=$(grep -E '^Test failed \(' "$out/$b.log" | sed -E 's/^Test failed \([^)]*\): //' | cut -c1-100 | paste -sd '；' - | sed 's/；/; /g')
  rows+=("| $b | $passed | ${secs}s | ${fails:-} |")
  echo "    $summary"
  grep -qE '^Test failed$' "$out/$b.log" && bad=1
done

{
  echo "# Test matrix"
  echo
  echo "Generated by \`scripts/matrix.sh\` on $(date +%Y-%m-%d) with $(bin/temper version 2>/dev/null | head -1); do not edit by hand."
  echo
  echo "| backend | passed | time | failures |"
  echo "|---|---:|---:|---|"
  printf '%s\n' "${rows[@]}"
} > MATRIX.md
echo "wrote MATRIX.md"
exit $bad
